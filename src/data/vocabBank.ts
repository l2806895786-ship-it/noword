function shuffleArray<T>(items: T[]): T[] {
  const arr = [...items];
  for (let i = arr.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

export function generateQuizRound(
  levelFilter: 'ALL' | CefrLevel = 'ALL',
  count = 10,
  customTargets?: VocabItem[]
): QuizQuestion[] {
  const filteredPool =
    levelFilter === 'ALL'
      ? VOCAB_BANK
      : VOCAB_BANK.filter((item) => item.level === levelFilter);

  const sourcePool = customTargets && customTargets.length > 0 ? customTargets : filteredPool;
  const targets = shuffleArray(sourcePool).slice(0, Math.min(count, sourcePool.length));

  return targets.map((target, index) => {
    const samePosDistractors = shuffleArray(
      VOCAB_BANK.filter(
        (candidate) =>
          candidate.id !== target.id &&
          candidate.meaning !== target.meaning &&
          candidate.pos === target.pos
      )
    );

    const fallbackDistractors = shuffleArray(
      VOCAB_BANK.filter(
        (candidate) =>
          candidate.id !== target.id &&
          candidate.meaning !== target.meaning &&
          candidate.pos !== target.pos
      )
    );

    const distractors = [...samePosDistractors, ...fallbackDistractors].slice(0, 3);
    const options = shuffleArray([target, ...distractors]);

    return {
      id: `${target.id}-${index}-${Date.now()}`,
      type: 'meaning',
      target,
      options,
    };
  });
}
